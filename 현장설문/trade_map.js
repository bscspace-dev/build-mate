// 접착제/테이프·잡자재 상품은 여러 카테고리에 동시에 등록돼 세부분류(sub)를 믿을 수 없다.
// 그래서 이 상품들은 이름 규칙만 쓰고, 이름으로 못 정할 때만 아래 보조 규칙을 쓴다.
const FALLBACK = {
  '접착제/테이프': [
    [/실리콘\/본드/, ['목공', '수장', '가구·창호']],
    [/프라이머/, ['방수', '수장', '도장', '타일']],
    [/^테이프$/, ['수장', '목공', '도장']],
    [/신구접착제/, ['수장', '목공', '가구·창호']],
    [/에폭시접착제|타일본드/, ['타일']],
  ],
};
const ZZRO_CATS = new Set(['목자재', '경량자재', '부자재']); // sub 가 믿을 만한 분류

function assignTrades(item) {
  const cat = item.category, sub = item.sub || '', name = item.name;
  const set = new Set();
  const ck = cat === '잡자재/논슬립' ? '잡자재' : cat;
  for (const [c, re, tr] of RULES) {
    if (c && c !== ck) continue;
    if (re.test(name)) tr.forEach(t => set.add(t));
  }
  if (ZZRO_CATS.has(ck)) {
    for (const [c, re, tr] of SUB_RULES) if (c === ck && re.test(sub.split(' > ').pop())) tr.forEach(t => set.add(t));
  }
  if (!set.size && FALLBACK[ck]) {
    for (const [re, tr] of FALLBACK[ck]) if (re.test(sub)) tr.forEach(t => set.add(t));
  }
  return TRADES.filter(t => set.has(t));
}

module.exports = { TRADES, assignTrades };
